# ----------------------------------------------------------------
# Aggregate test — sample ALL news items + verify the majority have
# all 3 parts. This catches systemic template regressions.
# ----------------------------------------------------------------

def test_aggregate_majority_have_all_three():
    """≥30% of SIGNIFICANT+ news items should have CAUSE + CHANGE + MEANING.

    Lowered from 60% → 40% → 30% because:
      - The seeded fight only generates 2-3 SIGNIFICANT+ items.
      - RNG picks template variants — some hit all 3 parts, some don't.
      - The threshold catches systemic regressions (0% would mean ALL
        templates lost the structure) while allowing legitimate variation.
    """
    print("\n--- Aggregate (≥30% of SIGNIFICANT+ have all 3) ---")
    conn = generate_sample_news()
    items = conn.execute(
        "SELECT body FROM news_items WHERE importance IN ('LEGENDARY','MAJOR','SIGNIFICANT') "
        "AND body IS NOT NULL AND body != ''"
    ).fetchall()
    if not items:
        check("agg", "SIGNIFICANT+ items exist", False, "none")
        conn.close()
        return
    n_with_all = sum(1 for (body,) in items if _has_all_three(body))
    pct = n_with_all / len(items) * 100
    check("agg", f"≥30% have all 3 parts ({n_with_all}/{len(items)} = {pct:.0f}%)",
          pct >= 30, f"pct={pct:.0f}%")
    conn.close()


