#!/usr/bin/env python3
"""HW4.6 — CAUSE→CHANGE→MEANING narrative quality rule (W37).

GPT's W37 feedback: "News should follow a CAUSE→CHANGE→MEANING
structure. CAUSE = what happened. CHANGE = what's different now.
MEANING = why it matters. Without all 3, the news feels flat."

This test verifies the rule on the news items generated by the news
engine. It does NOT require every item to hit all 3 parts perfectly
— it requires the TEMPLATES to support all 3 + samples the actual
news items to verify the structure is present in the aggregate.

The rule is enforced softly (informational, not gate-failing) because:
  1. Short news items (headline-only, like "X signs with Y") are
     legitimately CAUSE-only — the CHANGE + MEANING are implied.
  2. The voice layer already produces rich body text that hits all
     3 parts for SIGNIFICANT+ items.
  3. The test's job is to catch REGRESSIONS (a template that used to
     have all 3 parts losing one), not to enforce a rigid structure.

Runs on a fresh test DB. Verifies:
  - Title news (LEGENDARY) has all 3 parts in the body.
  - Fight news (SIGNIFICANT) has all 3 parts in the body.
  - Signing news (MAJOR) has all 3 parts in the body.
  - Retirement news (MAJOR) has all 3 parts in the body.
  - Memory resurfacing news (SIGNIFICANT) has all 3 parts in the body.
  - Injury news (SIGNIFICANT) has all 3 parts in the body.

The "3 parts" check is heuristic — it looks for:
  - CAUSE: a verb describing what happened ("wins", "loses", "signs",
    "retires", "injured", "calls out").
  - CHANGE: a phrase describing what's different now ("takes the
    title", "joins Alpha Combat", "sidelined for [phrase]").
  - MEANING: a phrase describing why it matters ("the legacy lives
    on", "the division has a new champion", "the road back begins
    now", "the storyline writes itself").
"""
import os
import re
import sqlite3
import subprocess
import sys
import random
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
SRC_DIR = PROJECT_DIR / "src"
DB_PATH = PROJECT_DIR / "data" / "cage_empire_test_narrative.db"

os.environ["CAGE_EMPIRE_DB_PATH"] = str(DB_PATH)
sys.path.insert(0, str(SRC_DIR))


# ----------------------------------------------------------------
# CAUSE→CHANGE→MEANING detectors (heuristic).
# ----------------------------------------------------------------

# CAUSE: action verbs in past tense.
_CAUSE_PATTERNS = [
    r"\b(wins|loses|signed|signs|retires|retired|injured|calls out|"
    r"called out|defeats|defeated|knocks out|submits|submitted|"
    r"claims|claimed|captures|captured|seizes|seized|vacates|vacated|"
    r"released|hires|hired|fires|fired|booked|announces|announced|"
    r"suffers|faces|halts|stopped|dismantles|earned|ascends)\b",
]

# CHANGE: phrases describing what's different now.
_CHANGE_PATTERNS = [
    r"\b(takes the title|takes the crown|joins|leaves|sidelined|"
    r"new champion|vacant|free agent|retired from|returns to|"
    r"steps into the role|ascends to|captures the title|"
    r"transition|moves to|signs with|no longer empty|"
    r"on the shelf|broken nose|orbital fracture|"
    r"the throne|the crown|the title|the belt)\b",
]

# MEANING: phrases describing why it matters.
_MEANING_PATTERNS = [
    r"\b(legacy|the road back|the storyline|the division|"
    r"the future|the past|the weight of|the comparisons|"
    r"the echoes|the torch|the crown|the throne|"
    r"what happens next|what it means|the implications|"
    r"the narrative|the memory|the history|the context|"
    r"hierarchy resets|hangs in the balance|"
    r"the version that built|the miles are starting|"
    r"the road back begins|the storyline writes itself|"
    r"the fans remember|the weight of everything)\b",
]


def _has_cause(text):
    return any(re.search(p, text, re.IGNORECASE) for p in _CAUSE_PATTERNS)


def _has_change(text):
    return any(re.search(p, text, re.IGNORECASE) for p in _CHANGE_PATTERNS)


def _has_meaning(text):
    return any(re.search(p, text, re.IGNORECASE) for p in _MEANING_PATTERNS)


def _has_all_three(text):
    return _has_cause(text) and _has_change(text) and _has_meaning(text)


def check(case, name, passed, detail=""):
    status = "PASS" if passed else "FAIL"
    print(f"  {case:8s}  {name:<55s} {status}  {detail}")
    return passed


# ----------------------------------------------------------------
# Test setup — generate news items by running the news engine.
# ----------------------------------------------------------------

def build_fresh_db():
    if DB_PATH.exists():
        DB_PATH.unlink()
    subprocess.run([sys.executable, str(SRC_DIR / "build_db.py")],
                   check=True, cwd=PROJECT_DIR)
    subprocess.run([sys.executable, str(SRC_DIR / "seed_data.py")],
                   check=True, cwd=PROJECT_DIR)


def get_conn():
    conn = sqlite3.connect(str(DB_PATH))
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def reset_bus():
    from event_bus import reset_bus as _reset
    _reset()
    for mod_name in ("news", "social", "rivalries", "punditry", "morale",
                      "suspensions", "agent_offers", "career_arc", "rival_ai",
                      "show_rating", "finance", "venues", "save_load",
                      "player_settings", "reputation"):
        try:
            mod = __import__(mod_name)
            if hasattr(mod, "register_subscribers"):
                mod.register_subscribers()
        except Exception:
            pass
    for svc_name in ("hof_svc", "pruning_svc", "memory_svc",
                      "punditry_svc", "rivalries_svc"):
        try:
            mod = __import__(f"services.{svc_name}", fromlist=[svc_name])
            if hasattr(mod, "register_subscribers"):
                mod.register_subscribers()
        except Exception:
            pass
    try:
        from interpretation import register_subscribers as _reg_interp
        _reg_interp()
    except Exception:
        pass


def generate_sample_news():
    """Resolve the seeded fight to generate title + fight + injury news."""
    build_fresh_db()
    conn = get_conn()
    reset_bus()

    # Advance clock to seeded event date (HW8.1).
    seeded = conn.execute(
        "SELECT event_date FROM events WHERE status='scheduled' ORDER BY event_id LIMIT 1"
    ).fetchone()
    if seeded and seeded[0]:
        conn.execute("UPDATE simulation_clock SET current_date=? WHERE clock_id=1", (seeded[0],))
        conn.commit()

    # Set decisive attributes for a clear winner.
    conn.execute("UPDATE fighter_attributes SET punch_power=90, chin=50 WHERE fighter_id=1")
    conn.execute("UPDATE fighter_attributes SET punch_power=30, chin=50 WHERE fighter_id=2")
    conn.commit()

    import app
    random.seed(42)
    app.resolve_next_fight(conn)
    conn.commit()
    return conn


# ----------------------------------------------------------------
# Tests — verify CAUSE→CHANGE→MEANING on each news type.
# ----------------------------------------------------------------

def test_title_news_has_all_three():
    """Title news (LEGENDARY) should have CAUSE + CHANGE + MEANING."""
    print("\n--- Title news (LEGENDARY) ---")
    conn = generate_sample_news()
    # Title news has importance=LEGENDARY (could be topic='title' or 'news_engine').
    items = conn.execute(
        "SELECT headline, body FROM news_items WHERE importance='LEGENDARY'"
    ).fetchall()
    check("title", "LEGENDARY news generated", len(items) >= 1,
          f"n={len(items)}")
    if not items:
        conn.close()
        return
    body = items[0][1]
    has_c = _has_cause(body)
    has_ch = _has_change(body)
    has_m = _has_meaning(body)
    check("title", "body has CAUSE", has_c, f"body={body[:80]}...")
    check("title", "body has CHANGE", has_ch, f"body={body[:80]}...")
    check("title", "body has MEANING", has_m, f"body={body[:80]}...")
    conn.close()


def test_fight_news_has_all_three():
    """Fight news (SIGNIFICANT) should have CAUSE + CHANGE + MEANING."""
    print("\n--- Fight news (SIGNIFICANT) ---")
