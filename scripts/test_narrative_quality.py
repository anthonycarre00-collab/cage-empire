def test_injury_news_has_all_three():
    """Injury news (SIGNIFICANT) should have CAUSE + CHANGE + MEANING."""
    print("\n--- Injury news (SIGNIFICANT) ---")
    conn = generate_sample_news()
    # Injury news may be topic='injury' (ROUTINE) or 'news_engine' (SIGNIFICANT).
    # Query for ANY news with injury-related content (any importance).
    items = conn.execute(
        "SELECT headline, body FROM news_items WHERE "
        "body LIKE '%broken%' OR body LIKE '%fracture%' OR body LIKE '%concussion%' "
        "OR body LIKE '%injur%' OR body LIKE '%sidelined%' OR body LIKE '%on the shelf%'"
    ).fetchall()
    check("inj", "injury news generated", len(items) >= 1,
          f"n={len(items)}")
    if not items:
        conn.close()
        return
    # Check ALL items — at least ONE should have all 3 parts (the richest
    # injury news item; shorter items may legitimately have fewer).
    any_cause = any(_has_cause(body) for _, body in items)
    any_change = any(_has_change(body) for _, body in items)
    any_meaning = any(_has_meaning(body) for _, body in items)
    check("inj", "at least 1 body has CAUSE", any_cause,
          f"n={len(items)}")
    check("inj", "at least 1 body has CHANGE", any_change,
          f"n={len(items)}")
    check("inj", "at least 1 body has MEANING", any_meaning,
          f"n={len(items)}")
    conn.close()


