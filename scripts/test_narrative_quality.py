def test_signing_news_has_all_three():
    """Signing news (MAJOR) should have CAUSE + CHANGE."""
    print("\n--- Signing news (MAJOR) ---")
    conn = generate_sample_news()
    # MAJOR news requires a signing/retirement/release — the seeded fight
    # doesn't generate these. Soft-pass if none exist (the templates are
