def register_subscribers():
    """Register the auto_save subscriber on the global event bus.

    Call once at startup (UI App.__init__, test setup, etc.). Safe
    to call multiple times — the event bus's subscribe() simply
    appends to its subscriber list. For test isolation, call
    reset_bus() first to clear any prior registrations.

    Subscribes to:
      TICK_ADVANCED → auto_save (monthly cadence check + rotating
                                  file pruning)
    """
    from event_bus import get_bus, Events
    bus = get_bus()
    bus.subscribe(
        Events.TICK_ADVANCED, auto_save,
        name="save_load.auto_save",
    )
