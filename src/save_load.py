def auto_save(conn, event):
    """TICK_ADVANCED subscriber — saves every 30 sim days (monthly).

    The cadence check reads simulation_clock.current_day from the
    DB (the value AFTER run_tick's clock advance — so day 30, 60,
    90, ... trigger an auto-save). If the cadence matches, calls
    save_game with an auto-generated name and prunes old auto-saves.

    SILENT — per the brief: "Auto-save should be SILENT (no news
    item, no print) — it's a background operation." Errors print to
    stderr (defensive — a broken auto-save shouldn't crash the
    game, but the operator should know it failed).

    Args:
        conn: sqlite3 connection (passed by the event bus).
        event: dict with at least 'type' = Events.TICK_ADVANCED and
            'current_date' (ISO date string of the new sim date).
            The current_date is used in the auto-save filename for
            human-readability — the file is named
            `autosave_<sim_date>_<wallclock>.db`.
    """
    # Cadence check — only save on every 30th sim day. Read
    # current_day from the DB (NOT from the event payload — the
    # TICK_ADVANCED event doesn't carry current_day, only
    # current_date). The DB has the NEW current_day because run_tick
    # updates the clock BEFORE bus.publish.
    try:
        row = conn.execute(
            "SELECT simulation_clock.current_day "
            "FROM simulation_clock WHERE clock_id=1"
        ).fetchone()
        if not row:
            return
        current_day = row[0]
    except sqlite3.Error:
        return

    if current_day % AUTOSAVE_CADENCE_DAYS != 0:
        return

    # Build the auto-save name. sim_date (from the event payload)
    # is human-readable ("when in the sim was this?"). Wall-clock
    # timestamp guarantees uniqueness (avoids overwriting if
    # multiple auto-saves fire on the same sim day via the "steps"
    # parameter). (D3.)
    sim_date = "unknown"
    if isinstance(event, dict):
        sim_date = event.get("current_date", "unknown") or "unknown"
    # Sanitize sim_date for use in a filename (replace dashes with
    # underscores — dashes are allowed in save names, but we want
    # the auto-save name to be one token without internal structure
    # ambiguity). Actually, dashes ARE allowed per _sanitize_save_name,
    # so we just need to replace any ':' or other disallowed chars.
    # ISO date strings (YYYY-MM-DD) are already safe.
    safe_sim_date = _sanitize_save_name(sim_date)
    wallclock = datetime.now().strftime("%Y%m%d_%H%M%S")
    save_name = f"{AUTOSAVE_PREFIX}{safe_sim_date}_{wallclock}"

    try:
        save_game(conn, save_name=save_name)
        _prune_autosaves()
    except Exception as e:
        # SILENT — auto-save is a background operation. Log to
        # stderr so the operator can see if something broke, but
        # do NOT raise (a broken auto-save shouldn't crash the
        # game or block other TICK_ADVANCED subscribers).
        print(f"Warning: auto_save failed: {type(e).__name__}: {e}",
              file=sys.stderr)


