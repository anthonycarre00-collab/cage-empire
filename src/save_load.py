"""CAGE EMPIRE Save/Load System (Stage 5 — Task ID Stage5-SaveLoad).

This module wires the save/load functionality. The game currently has
NO save/load — the DB IS the game state. Saving = backing up the DB
file to data/saves/{name}.db; loading = copying that file back to the
active DB path. This is fast (the DB is ~25MB) and preserves the
exact state (every table, every row, every column — no serialization
loss).

CONVENTIONS compliance:
  §5  — One table-group per task. This task adds NO new tables — the
        DB IS the save state. Per the brief: "Do NOT add new tables
        — the DB IS the save state." All save/load metadata lives
        as JSON files alongside the .db files (one .json per save).
  §6  — Smoke test protocol followed. The acceptance test rebuilds
        the DB, seeds, then exercises save/load.
  §10 — Dynamic-version pattern. The acceptance test reads
        build_db.CODE_SCHEMA_VERSION at test time (no hardcoded
        '3.6.0' string). This module also writes the schema_version
        into the save metadata at save time (queried from
        schema_meta, not hardcoded).
  §13 — Design Law: Investment pillar (the player's progress — the
        fighters they scouted, the champions they crowned, the
        market heat they built — is preserved across save/load.
        Without save/load, every game session is ephemeral; with
        it, the player's empire is durable. The "remember that
        championship reign" storyline only matters if the player
        can come back to it tomorrow. This is the foundation of
        the Historian fantasy: "The world remembers what I built"
        — the player must first be able to RETURN to what they
        built.)
  §14 — Voice Layer: save/load is internal (file names, metadata
        JSON). Raw numbers ARE allowed in the JSON metadata per
        the brief ("save/load is internal (file names, metadata),
        so raw numbers are OK in the JSON metadata"). No
        player-facing text is generated by this module.
  §15 — Event Bus: auto_save subscribes to TICK_ADVANCED. No new
        inline side effects in run_tick. The auto-save fires as a
        downstream subscriber, SILENTLY (no news item, no print —
        background operation per the brief).

SAVE METADATA JSON format:
  {
      "save_name": "my_save",
      "timestamp": "2026-07-23T18:30:00",
      "sim_date": "2026-08-15",
      "promotion_name": "Alpha Combat Federation",
      "current_cash": 45000000,
      "fighter_count": 4000,
      "event_count": 25,
      "schema_version": "3.6.0"
  }

AUTO-SAVE:
  - Cadence: every 30 sim days (monthly). The cadence check uses
    simulation_clock.current_day (the value AFTER run_tick's clock
    advance — so day 30, 60, 90, ... trigger an auto-save).
  - File naming: `autosave_<sim_date>_<wallclock>.db` — the sim_date
    is human-readable (what sim day was this?), the wall-clock
    timestamp guarantees uniqueness (avoids overwriting if multiple
    auto-saves fire on the same sim day via the "steps" parameter).
  - Rotation: keeps only the last 3 auto-saves (by mtime). Older
    auto-saves are deleted (both .db and .json). The "rotating"
    pattern means the player always has 3 recent restore points.
  - SILENT: no news item, no print to stdout (errors print to
    stderr — defensive, auto-save should never crash the game).

USAGE:
  from save_load import (save_game, load_game, list_saves,
      delete_save, auto_save, register_subscribers)

  # Manual save
  save_game(conn, save_name="my_save")
  # → writes data/saves/my_save.db + data/saves/my_save.json

  # Manual save with auto-generated name (timestamp)
  save_game(conn)
  # → writes data/saves/save_<YYYYMMDD_HHMMSS>.db

  # List saves
  saves = list_saves()
  # → [{"name": "my_save", "timestamp": ..., "sim_date": ..., ...}, ...]

  # Load
  new_conn = load_game("my_save")
  # → copies data/saves/my_save.db back to data/cage_empire.db,
  #   returns a fresh sqlite3.Connection

  # Delete
  delete_save("my_save")
  # → removes data/saves/my_save.db + .json

  # Auto-save (registered automatically via register_subscribers)
  register_subscribers()
  # → on every TICK_ADVANCED, auto_save fires; monthly ticks
  #   trigger a rotating auto-save to data/saves/autosave_*.db

DESIGN DECISIONS:
  - shutil.copy2 (NOT database dumps). The brief mandates this —
    the DB is small (~25MB), and a file copy preserves the EXACT
    state (every table, every row, every column, including
    sqlite_sequence auto-increment counters). A dump + reload would
    lose AUTOINCREMENT counters and could reorder rows. File copy
    is byte-for-byte identical. (D1.)
  - conn.commit() BEFORE shutil.copy2. This flushes any pending
    transaction (e.g., run_tick's clock advance + retirements +
    contract expiries + injury recoveries + training camps + scouting
    reports) to the file BEFORE the copy. Without this, an auto-save
    fired by the TICK_ADVANCED subscriber would capture the PRE-tick
    state (because run_tick commits AFTER bus.publish). With it,
    the auto-save captures the post-tick state. The subsequent
    conn.commit() in run_tick is a no-op (no pending transaction).
    (D2.)
  - Auto-save file naming uses BOTH sim_date AND wall-clock
    timestamp. sim_date alone could collide if the player advances
    multiple months via the "steps" parameter in a single run_tick
    call (each month's TICK_ADVANCED fires within microseconds).
    Wall-clock timestamp guarantees uniqueness. The sim_date prefix
    makes the file human-readable ("autosave_2026-09-15_*.db" tells
    the player when in the SIM this save was made). (D3.)
  - Save name sanitization: only [a-zA-Z0-9_-] allowed. Disallowed
    chars (spaces, slashes, dots, etc.) are replaced with '_'. This
    prevents path traversal (../etc/passwd) and weird filesystem
    behavior. The brief mandates "no spaces, no special chars".
    (D4.)
  - list_saves() reads metadata from .json files, NOT from the .db
    files. This is fast (no DB connections opened) and works even
    if the .db file is corrupted (the metadata is preserved). The
    .json file is the source of truth for save metadata.
  - load_game() overwrites the active DB path. The caller is
    responsible for closing any existing connection BEFORE calling
    load_game — on Windows, you can't overwrite a file that's open
    by another process. The function returns a NEW connection to
    the restored DB. (D5.)
  - Auto-save is SILENT. Per the brief: "Auto-save should be SILENT
    (no news item, no print) — it's a background operation." Errors
    print to stderr (defensive — a broken auto-save shouldn't crash
    the game, but the operator should know it failed).
  - auto_save signature is (conn, event) per the event bus
    subscriber convention (every subscriber takes (conn, event)).
    The brief writes "auto_save(conn)" as shorthand — the event
    payload is used to extract the sim_date for the filename.
    (D6.)
"""

