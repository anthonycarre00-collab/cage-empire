def save_game(conn, save_name=None):
    """Save the current DB to data/saves/{save_name}.db.

    Copies the active DB file to data/saves/{save_name}.db using
    shutil.copy2 (byte-for-byte copy preserving metadata). Also
    writes a save metadata JSON file alongside the .db file with
    the sim state at save time.

    Args:
        conn: sqlite3 connection to the active DB. Used for two
            purposes: (1) conn.commit() to flush any pending
            transaction before the copy (so the file has the
            latest state — critical when auto_save fires as a
            TICK_ADVANCED subscriber before run_tick's final
            commit); (2) querying the save metadata fields
            (sim_date, promotion_name, current_cash, fighter_count,
            event_count, schema_version).
        save_name: name for the save file. If None, uses a
            timestamp-based name (save_YYYYMMDD_HHMMSS). The name
            is sanitized per _sanitize_save_name — only [a-zA-Z0-9_-]
            allowed, disallowed chars replaced with '_'.

    Returns:
        The sanitized save_name (str). Useful when save_name=None
        — the caller can learn what name was assigned.

    Raises:
        sqlite3.Error: if the DB connection is broken (the commit
            or metadata queries fail with a non-recoverable error).
        OSError: if the file copy fails (e.g., disk full, permission
            denied).
    """
    _ensure_saves_dir()

    # Generate save name if not provided.
    if save_name is None:
        save_name = datetime.now().strftime("save_%Y%m%d_%H%M%S")

    save_name = _sanitize_save_name(save_name)

    # Commit any pending transactions so the file copy has the
    # latest state. CRITICAL when auto_save fires as a TICK_ADVANCED
    # subscriber — run_tick commits AFTER bus.publish, so without
    # this commit, the auto-save would capture the PRE-tick state
    # (D2). The subsequent conn.commit() in run_tick is a no-op.
    try:
        conn.commit()
    except sqlite3.Error:
        # A broken commit shouldn't crash save_game — the file
        # copy may still succeed (the journal may have the data
        # even if commit failed). Worst case, the save is stale.
        pass

    save_db_path = SAVES_DIR / f"{save_name}.db"

    # Copy the DB file (per the brief: shutil.copy2, NOT database
    # dumps). shutil.copy2 preserves file metadata (mtime, mode).
    shutil.copy2(DB_PATH, save_db_path)

    # Build + write metadata JSON.
    _write_metadata(save_name, conn)

    return save_name


def load_game(save_name):
    """Load data/saves/{save_name}.db back to the active DB path.

    Copies the save file back to DB_PATH (data/cage_empire.db),
    overwriting the current DB. Returns a NEW sqlite3.Connection
    to the restored DB. The caller is responsible for closing any
    existing connection BEFORE calling load_game — on Windows,
    you can't overwrite a file that's open by another process.

    Args:
        save_name: name of the save to load. Sanitized per
            _sanitize_save_name.

    Returns:
        sqlite3.Connection — a fresh connection to the restored DB,
        with PRAGMA foreign_keys = ON (matching the convention used
        by App.__init__ and tick_processor.main).

    Raises:
        FileNotFoundError: if the save file doesn't exist.
        OSError: if the file copy fails.
    """
    _ensure_saves_dir()

    save_name = _sanitize_save_name(save_name)
    save_db_path = SAVES_DIR / f"{save_name}.db"

    if not save_db_path.exists():
        raise FileNotFoundError(
            f"Save file not found: {save_db_path} (save_name={save_name!r})"
        )

    # Copy the save file back to the active DB path. shutil.copy2
    # preserves file metadata (mtime, mode). The active DB file is
    # overwritten in place.
    shutil.copy2(save_db_path, DB_PATH)

    # Open a new connection to the restored DB. The caller is
    # responsible for closing any prior connection (we cannot do
    # it from here — we don't have a reference to it).
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def list_saves():
    """Return a list of save metadata dicts.

    Iterates over all .json files in data/saves/, reads each one,
    and returns a list of metadata dicts. Sorted by timestamp DESC
    (newest first) so the UI can display the most recent saves at
    the top.

    Returns:
        List of dicts, each with keys:
            name (str):          save_name (sanitized).
            timestamp (str|None): ISO timestamp of the save.
            sim_date (str|None):  simulation_clock.current_date at save.
            promotion (str):      promotions.name for promotion_id=1.
            cash (float|int):     promotions.current_cash for promotion_id=1.
            fighters (int):       COUNT(*) FROM fighters.
            events (int):         COUNT(*) FROM events.
            schema_version (str): schema_meta.schema_version.
            is_autosave (bool):   True if name starts with AUTOSAVE_PREFIX.
            db_path (str):        absolute path to the .db file.
    """
    _ensure_saves_dir()

    saves = []
    for json_path in SAVES_DIR.glob("*.json"):
        try:
            with open(json_path, "r", encoding="utf-8") as f:
                meta = json.load(f)
        except (json.JSONDecodeError, OSError):
            # Skip corrupted JSON — the .db file may still be
            # valid, but we can't display metadata without the
            # JSON. The UI can fall back to showing the filename.
            continue

        name = meta.get("save_name", json_path.stem)
        saves.append({
            "name": name,
            "timestamp": meta.get("timestamp"),
            "sim_date": meta.get("sim_date"),
            "promotion": meta.get("promotion_name"),
            "cash": meta.get("current_cash"),
            "fighters": meta.get("fighter_count"),
            "events": meta.get("event_count"),
            "schema_version": meta.get("schema_version"),
            "is_autosave": name.startswith(AUTOSAVE_PREFIX),
            "db_path": str(SAVES_DIR / f"{name}.db"),
        })

    # Sort by timestamp DESC (newest first). Missing timestamps
    # sort to the end (treated as empty string).
    saves.sort(key=lambda s: s.get("timestamp") or "", reverse=True)
    return saves


def delete_save(save_name):
    """Delete a save file (both .db and .json).

    Args:
        save_name: name of the save to delete. Sanitized per
            _sanitize_save_name.

    Returns:
        True if any file was deleted (the .db OR .json), False if
        no save with that name existed.
    """
    save_name = _sanitize_save_name(save_name)
    save_db_path = SAVES_DIR / f"{save_name}.db"
    save_json_path = SAVES_DIR / f"{save_name}.json"

    deleted = False
    if save_db_path.exists():
        try:
            save_db_path.unlink()
            deleted = True
        except OSError:
            pass
    if save_json_path.exists():
        try:
            save_json_path.unlink()
            deleted = True
        except OSError:
            pass
    return deleted


