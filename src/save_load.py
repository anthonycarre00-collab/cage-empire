def _ensure_saves_dir():
    """Create data/saves/ if it doesn't exist.

    Idempotent — mkdir(parents=True, exist_ok=True) is a no-op if
    the directory already exists. The directory is in .gitignore
    (line 35 of .gitignore: `data/saves/`), so saves are NEVER
    committed to the repo.
    """
    SAVES_DIR.mkdir(parents=True, exist_ok=True)


def _sanitize_save_name(save_name):
    """Sanitize a save name — only [a-zA-Z0-9_-] allowed.

    Per the brief: "The save file name should be safe (no spaces,
    no special chars)." This function enforces that:
      - Strips leading/trailing whitespace.
      - Replaces any char that's not [a-zA-Z0-9_-] with '_'.
      - Truncates to _MAX_SAVE_NAME_LEN chars.
      - Falls back to "save" if the result is empty.

    Args:
        save_name: raw user-provided name (or None).

    Returns:
        Sanitized name (str). Always non-empty.
    """
    if save_name is None:
        return "save"
    name = str(save_name).strip()
    if not name:
        return "save"
    name = _SAVE_NAME_SAFE_RE.sub("_", name)
    # Strip leading underscores (caused by leading special chars)
    # to keep the name readable.
    name = name.lstrip("_")
    if not name:
        return "save"
    # Truncate to max length.
    if len(name) > _MAX_SAVE_NAME_LEN:
        name = name[:_MAX_SAVE_NAME_LEN]
    return name


def _query_save_metadata(conn):
    """Query the DB for save metadata fields.

    Per the brief: "query the DB for: simulation_clock.current_date,
    promotions.name + current_cash (for promotion_id=1), COUNT(*)
    FROM fighters, COUNT(*) FROM events." The schema_version is
    also queried from schema_meta (per the brief's metadata JSON
    example).

    Defensive — each query is wrapped in try/except so a missing
    table (e.g., a partial DB) doesn't crash the save. This is
    important because save_game may be called on a DB that's mid-
    migration or partially built.

    Args:
        conn: sqlite3 connection.

    Returns:
        Dict with keys: sim_date, promotion_name, current_cash,
        fighter_count, event_count, schema_version. Missing values
        default to None / 0 / "unknown".
    """
    meta = {
        "sim_date": None,
        "promotion_name": "Unknown",
        "current_cash": 0,
        "fighter_count": 0,
        "event_count": 0,
        "schema_version": "unknown",
    }

    # sim_date — simulation_clock.current_date (qualified per
    # Task 14.7 to avoid the bare-current_date SQLite quirk).
    try:
        row = conn.execute(
            "SELECT simulation_clock.current_date "
            "FROM simulation_clock WHERE clock_id=1"
        ).fetchone()
        if row and row[0]:
            meta["sim_date"] = row[0]
    except sqlite3.Error:
        pass

    # promotion_name + current_cash for the player's promotion.
    try:
        row = conn.execute(
            "SELECT name, current_cash FROM promotions WHERE promotion_id=?",
            (PLAYER_PROMOTION_ID,),
        ).fetchone()
        if row:
            if row[0]:
                meta["promotion_name"] = row[0]
            meta["current_cash"] = row[1] if row[1] is not None else 0
    except sqlite3.Error:
        pass

    # fighter_count.
    try:
        row = conn.execute("SELECT COUNT(*) FROM fighters").fetchone()
        if row:
            meta["fighter_count"] = row[0]
    except sqlite3.Error:
        pass

    # event_count.
    try:
        row = conn.execute("SELECT COUNT(*) FROM events").fetchone()
        if row:
            meta["event_count"] = row[0]
    except sqlite3.Error:
        pass

    # schema_version — from schema_meta (the canonical version
    # recorded by build_db.py on every fresh + migrate build).
    try:
        row = conn.execute(
            "SELECT schema_version FROM schema_meta "
            "WHERE schema_name='cage_empire'"
        ).fetchone()
        if row and row[0]:
            meta["schema_version"] = row[0]
    except sqlite3.Error:
        pass

    return meta


def _write_metadata(save_name, conn):
    """Build + write the save metadata JSON.

    The JSON file lives at data/saves/{save_name}.json (alongside
    the .db file). Per the brief's metadata JSON format example.

    Args:
        save_name: sanitized save name (used for the filename).
        conn: sqlite3 connection (for querying sim state).
    """
    meta_path = SAVES_DIR / f"{save_name}.json"
    metadata = {
        "save_name": save_name,
        "timestamp": datetime.now().isoformat(timespec="seconds"),
    }
    metadata.update(_query_save_metadata(conn))
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=4, default=str)
    return metadata


def _prune_autosaves():
    """Keep only the last N auto-saves (by mtime).

    Per the brief: "Keeps only the last 3 auto-saves (rotating)."
    Lists all files matching `autosave_*.db`, sorts by mtime DESC,
    and deletes all but the newest AUTOSAVE_MAX_FILES. Both the
    .db and .json files are deleted for pruned saves.

    Silent — pruning errors are swallowed (a stuck file shouldn't
    crash the auto-save path).
    """
    autosave_files = list(SAVES_DIR.glob(f"{AUTOSAVE_PREFIX}*.db"))
    if len(autosave_files) <= AUTOSAVE_MAX_FILES:
        return

    # Sort by mtime DESC (newest first).
    autosave_files.sort(key=lambda p: p.stat().st_mtime, reverse=True)

    # Delete all but the newest N.
    for old_db_path in autosave_files[AUTOSAVE_MAX_FILES:]:
        try:
            old_db_path.unlink()
        except OSError:
            pass
        # Also delete the matching .json metadata file.
        old_json_path = old_db_path.with_suffix(".json")
        if old_json_path.exists():
            try:
                old_json_path.unlink()
            except OSError:
                pass


