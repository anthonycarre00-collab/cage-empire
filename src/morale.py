def _process_camp_completed(conn, event):
    """Subscriber for CAMP_COMPLETED. +3 morale (training went well)."""
    fighter_id = event.get('fighter_id')
    if fighter_id is None:
        return
    m = _get_morale(conn, fighter_id)
    _set_morale(conn, fighter_id, m + 3, update_snapshot=True)


def _process_camp_injury(conn, event):
    """Subscriber for CAMP_INJURY. -5 morale (training setback)."""
    fighter_id = event.get('fighter_id')
    if fighter_id is None:
        return
    m = _get_morale(conn, fighter_id)
    _set_morale(conn, fighter_id, m - 5, update_snapshot=True)


def _process_fight_cancelled(conn, event):
    """Subscriber for FIGHT_CANCELLED (weight cut miss).

    Fighter who missed weight: -5 morale.
    Opponent: -3 morale (frustration).

    NOTE: FIGHT_CANCELLED is not yet published by app.py (the weight
    cut cancellation path returns early before the FIGHT_RESOLVED
    publish). Phase A5 will wire news coverage and publish the event.
    This subscriber is registered now for forward-compat.
    """
    missed_fighter_id = event.get('missed_fighter_id')
    opponent_id = event.get('opponent_id')
    if missed_fighter_id is not None:
        m = _get_morale(conn, missed_fighter_id)
        _set_morale(conn, missed_fighter_id, m - 5, update_snapshot=True)
    if opponent_id is not None:
        m = _get_morale(conn, opponent_id)
        _set_morale(conn, opponent_id, m - 3, update_snapshot=True)


