# Internal helpers
# ----------------------------------------------------------------

def _clamp_morale(v):
    """Clamp a morale value to [MORALE_FLOOR, MORALE_CEIL]."""
    return max(MORALE_FLOOR, min(MORALE_CEIL, int(v)))


def _clamp_personality(v):
    """Clamp a personality field value to [PERSONALITY_FLOOR, PERSONALITY_CEIL].

    Stage5-Final — the 6 stale personality fields (grit, ambition,
    loyalty, resilience, travel_comfort, fatigue_tolerance) are clamped
    tighter than the schema's 0-100 CHECK. Preserves REAL values
    (travel_comfort is stored as REAL for 0.5 increments) by skipping
    the int() conversion when the input is a float.
    """
    if isinstance(v, float):
        return float(max(PERSONALITY_FLOOR, min(PERSONALITY_CEIL, v)))
    return max(PERSONALITY_FLOOR, min(PERSONALITY_CEIL, int(v)))


def _set_personality_field(conn, fighter_id, field, new_value,
                            update_snapshot=True):
    """Update a single fighter_personality field (Stage5-Final).

    Defensive — only allows the 6 personality fields owned by this
    task (grit, ambition, loyalty, resilience, travel_comfort,
    fatigue_tolerance). The whitelist prevents accidental writes to
    morale / aggression / composure (which have their own writers).

    Args:
        conn: sqlite3 connection (caller commits).
        fighter_id: the fighter to update.
        field: one of the 6 personality field names.
        new_value: the target value (will be clamped to [10, 95]).
        update_snapshot: if True (default), refresh the fighter's
            descriptor snapshot so the UI sees the new tier.
    """
    _ALLOWED = {
        "grit", "ambition", "loyalty", "resilience",
        "travel_comfort", "fatigue_tolerance",
    }
    if field not in _ALLOWED:
        return  # defensive — caller bug, refuse to write
    clamped = _clamp_personality(new_value)
    conn.execute(
        f"UPDATE fighter_personality SET {field}=? "
        f"WHERE fighter_id=?",
        (clamped, fighter_id),
    )
    if update_snapshot:
        _refresh_snapshot(conn, fighter_id)


def _get_morale(conn, fighter_id):
    """Return the fighter's current morale (default 50 if no row)."""
    row = conn.execute(
        "SELECT morale FROM fighter_personality WHERE fighter_id=?",
        (fighter_id,),
    ).fetchone()
    return row[0] if row and row[0] is not None else 50


def _set_morale(conn, fighter_id, new_morale, update_snapshot=True):
    """Update a fighter's morale (clamped to [10, 95]).

    Args:
        conn: sqlite3 connection (caller commits).
        fighter_id: the fighter whose morale to update.
        new_morale: the target morale value (will be clamped).
        update_snapshot: if True (default), refresh the fighter's
            descriptor snapshot so the UI sees the new morale tier
            immediately. Set False when batching many updates —
            the caller can refresh the snapshot once at the end.
    """
    clamped = _clamp_morale(new_morale)
    conn.execute(
        "UPDATE fighter_personality SET morale=? WHERE fighter_id=?",
        (clamped, fighter_id),
    )
    if update_snapshot:
        _refresh_snapshot(conn, fighter_id)


def _refresh_snapshot(conn, fighter_id):
    """Refresh the fighter's descriptor snapshot (lazy-import to avoid
    circular dependency with app.py)."""
    try:
        from app import update_fighter_descriptor_snapshot
        update_fighter_descriptor_snapshot(conn, fighter_id)
    except ImportError:
        pass  # defensive — app.py not available (headless test?)


def _streak(conn, fighter_id):
    """Return (win_streak, loss_streak) for the fighter (0,0 if no row)."""
    row = conn.execute(
        "SELECT win_streak, loss_streak FROM fighter_career WHERE fighter_id=?",
        (fighter_id,),
    ).fetchone()
    if not row:
        return 0, 0
    return row[0] or 0, row[1] or 0


def _days_since_last_fight(conn, fighter_id, current_date):
    """Days since the fighter's most recent fight (None if never fought)."""
    row = conn.execute(
        "SELECT MAX(event_date) FROM fight_history WHERE fighter_id=?",
        (fighter_id,),
    ).fetchone()
    if not row or not row[0]:
        return None
    try:
        last = datetime.strptime(row[0], "%Y-%m-%d")
        cur = datetime.strptime(current_date, "%Y-%m-%d")
        return (cur - last).days
    except (ValueError, TypeError):
        return None


def _is_weekly_tick(conn):
    """Return True if the current sim day is the last day of a sim week.

    The sim runs daily ticks; we treat days 7, 14, 21, ... as the
    weekly tick (end of week). This is the natural cadence for the
    morale drift / ring-rust / win-streak-bonus logic — applying
    them daily would shift morale too fast.
    """
    row = conn.execute(
        "SELECT simulation_clock.current_day "
        "FROM simulation_clock WHERE clock_id=1"
    ).fetchone()
    if not row or row[0] is None:
        return False
    return (row[0] % 7) == 0


