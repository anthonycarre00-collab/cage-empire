def _process_fight(conn, event):
    """Subscriber for FIGHT_RESOLVED — A1 morale + A10 dynamic fields.

    Sequence:
      1. Apply win/loss/draw morale changes to both fighters.
      2. Scan injuries table for new injuries for this fight_id and
         apply severity-scaled morale penalties (INJURY_CREATED
         surrogate — the engine doesn't publish INJURY_CREATED).
      3. Update A10 dynamic fields (marketability, fan_friendliness,
         consistency, clutch_factor, promo_boost).
      4. Refresh descriptor snapshots for both fighters (one pass).
    """
    fight_id = event.get('fight_id')
    if fight_id is None:
        return

    winner_id = event.get('winner_id')
    loser_id = event.get('loser_id')
    a_id = event.get('fighter_a_id')
    b_id = event.get('fighter_b_id')
    result_type = (event.get('result_type') or '').lower()
    is_title_fight = bool(event.get('is_title_fight'))
    title_changed = bool(event.get('title_changed'))

    # --- A1.1 — morale for fight outcome ---
    if result_type == 'draw' or winner_id is None:
        # Draw: +1 both (moral victory for the underdog).
        for fid in (a_id, b_id):
            if fid is None:
                continue
            m = _get_morale(conn, fid)
            _set_morale(conn, fid, m + 1, update_snapshot=False)
    else:
        # Winner base: +5 (or +15 for title win).
        if is_title_fight and title_changed:
            win_base = 15
        else:
            win_base = 5
        # Winning-streak bonus: +2 per consecutive win beyond the
        # first, capped at +6. The streak counter has already been
        # incremented by resolve_next_fight (side effect runs before
        # the event is published), so w_streak reflects the post-
        # fight streak.
        w_streak, _ = _streak(conn, winner_id)
        win_bonus = min(WIN_STREAK_BONUS_CAP,
                        max(0, w_streak - 1) * WIN_STREAK_BONUS_PER)
        m = _get_morale(conn, winner_id)
        _set_morale(conn, winner_id,
                    m + win_base + win_bonus, update_snapshot=False)

        # Loser base: -5 (KO/TKO: -10, submission: -8).
        if result_type in ('ko_tko', 'ko', 'tko'):
            loss_base = -10
        elif result_type == 'submission':
            loss_base = -8
        else:
            loss_base = -5
        # Losing-streak modifier: -3 per consecutive loss beyond the
        # first, capped at -9.
        _, l_streak = _streak(conn, loser_id)
        loss_penalty = max(LOSS_STREAK_PENALTY_CAP,
                           LOSS_STREAK_PENALTY_PER * max(0, l_streak - 1))
        m = _get_morale(conn, loser_id)
        _set_morale(conn, loser_id,
                    m + loss_base + loss_penalty, update_snapshot=False)

    # --- A1.2 — injury morale penalty (INJURY_CREATED surrogate) ---
    # The engine creates injuries via _check_post_fight_injuries just
    # before publishing FIGHT_RESOLVED. We scan the injuries table for
    # new rows tied to this fight and apply -1.0 morale per severity
    # point, capped at -10 per injury.
    inj_rows = conn.execute(
        "SELECT fighter_id, severity FROM injuries WHERE fight_id=?",
        (fight_id,),
    ).fetchall()
    for inj_fighter_id, sev in inj_rows:
        if inj_fighter_id is None:
            continue
        severity = sev if sev is not None else 5
        penalty = -min(10, int(severity * 1.0))
        m = _get_morale(conn, inj_fighter_id)
        _set_morale(conn, inj_fighter_id, m + penalty, update_snapshot=False)

    # --- A10 — dynamic meta-fields on the fighters table ---
    _update_fight_dynamic_fields(
        conn, fight_id, winner_id, loser_id, a_id, b_id,
        result_type, is_title_fight, title_changed,
    )

    # --- Stage5-Final — stale personality fields (grit, ambition,
    # resilience, travel_comfort) on FIGHT_RESOLVED ---
    _update_fight_personality_fields(
        conn, fight_id, winner_id, loser_id, a_id, b_id,
        result_type, is_title_fight, title_changed,
    )

    # --- Refresh descriptor snapshots for both fighters (one pass) ---
    # Done last so the snapshot reflects both the morale change AND
    # any dynamic-field changes (which feed the fighter_data dict).
    for fid in (a_id, b_id):
        if fid is None:
            continue
        _refresh_snapshot(conn, fid)


def _update_fight_dynamic_fields(conn, fight_id, winner_id, loser_id,
                                  a_id, b_id, result_type,
                                  is_title_fight, title_changed):
    """Update fighters.* columns based on a resolved fight (A10).

    Per the brief:
      marketability: +2 per win, +5 per title win, -1 per loss,
                     -10 per suspension (suspensions not yet
                     implemented — reserved).
      fan_friendliness: +1 per KO/submission win, -1 per boring
                        decision loss, +2 per exciting fight
                        (>10 beats in round 1).
      consistency: +0.5 per fight fought (cap at 90, floor at seed
                   value — we only increase, so the floor is
                   naturally maintained).
      clutch_factor: +2 if win in title fight, -2 if loss in title
                     fight (cap 90, floor 20).
      promo_boost: +1 per social post with engagement > 50
                   (counted between previous fight and this one).
    """
    is_finish = result_type in ('ko_tko', 'ko', 'tko', 'submission')

    # Determine "exciting fight" — >10 beats in round 1.
    exciting = False
    if fight_id is not None:
        row = conn.execute(
            "SELECT COUNT(*) FROM fight_beats "
            "WHERE fight_id=? AND round_number=1",
            (fight_id,),
        ).fetchone()
        if row and row[0] > EXCITING_FIGHT_BEAT_THRESHOLD:
            exciting = True

    # ---- marketability ----
    if winner_id is not None:
        mkt = conn.execute(
            "SELECT marketability FROM fighters WHERE fighter_id=?",
            (winner_id,),
        ).fetchone()
        if mkt:
            if is_title_fight and title_changed:
                bump = 5
            elif is_title_fight:
                bump = 3  # title defense win (not a title change)
            else:
                bump = 2
            new_mkt = min(100, (mkt[0] if mkt[0] is not None else 50) + bump)
            conn.execute(
                "UPDATE fighters SET marketability=?, "
                "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                (new_mkt, winner_id),
            )
    if loser_id is not None:
        mkt = conn.execute(
            "SELECT marketability FROM fighters WHERE fighter_id=?",
            (loser_id,),
        ).fetchone()
        if mkt:
            new_mkt = max(0, (mkt[0] if mkt[0] is not None else 50) - 1)
            conn.execute(
                "UPDATE fighters SET marketability=?, "
                "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                (new_mkt, loser_id),
            )

    # ---- fan_friendliness ----
    if winner_id is not None:
        ff = conn.execute(
            "SELECT fan_friendliness FROM fighters WHERE fighter_id=?",
            (winner_id,),
        ).fetchone()
        if ff:
            bump = 0
            if is_finish:
                bump += 1   # KO/submission win = exciting for fans
            if exciting:
                bump += 2   # bonus for being in an exciting fight
            new_ff = min(100, max(0,
                (ff[0] if ff[0] is not None else 50) + bump))
            conn.execute(
                "UPDATE fighters SET fan_friendliness=?, "
                "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                (new_ff, winner_id),
            )
    if loser_id is not None:
        ff = conn.execute(
            "SELECT fan_friendliness FROM fighters WHERE fighter_id=?",
            (loser_id,),
        ).fetchone()
        if ff:
            bump = 0
            if not is_finish and not exciting:
                bump -= 1   # boring decision loss
            if exciting:
                bump += 2   # bonus for being in an exciting fight
            new_ff = min(100, max(0,
                (ff[0] if ff[0] is not None else 50) + bump))
            conn.execute(
                "UPDATE fighters SET fan_friendliness=?, "
                "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                (new_ff, loser_id),
            )

    # ---- consistency: +0.5 per fight fought (cap 90) ----
    # SQLite INTEGER column accepts REAL values (NUMERIC affinity),
    # so +0.5 writes 50.5, 51.0, 51.5, ... naturally. The cap is 90.
    for fid in (a_id, b_id):
        if fid is None:
            continue
        row = conn.execute(
            "SELECT consistency FROM fighters WHERE fighter_id=?",
            (fid,),
        ).fetchone()
        if not row:
            continue
        cur_cons = row[0] if row[0] is not None else 50
        new_cons = min(float(CONSISTENCY_CAP), cur_cons + 0.5)
        if new_cons != cur_cons:
            conn.execute(
                "UPDATE fighters SET consistency=?, "
                "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                (new_cons, fid),
            )

    # ---- clutch_factor: +2 title-fight win, -2 title-fight loss ----
    if is_title_fight:
        for fid, delta in ((winner_id, +2), (loser_id, -2)):
            if fid is None:
                continue
            row = conn.execute(
                "SELECT clutch_factor FROM fighters WHERE fighter_id=?",
                (fid,),
            ).fetchone()
            if not row:
                continue
            cur_cf = row[0] if row[0] is not None else 50
            new_cf = max(CLUTCH_FACTOR_FLOOR,
                         min(CLUTCH_FACTOR_CAP, cur_cf + delta))
            if new_cf != cur_cf:
                conn.execute(
                    "UPDATE fighters SET clutch_factor=?, "
                    "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                    (new_cf, fid),
                )

    # ---- promo_boost: +1 per social post with engagement > 50 ----
    # Count viral posts between the fighter's previous fight and this
    # one. This is a per-fight window so the boost accumulates over a
    # career (each fight picks up the viral posts since the last one).
    for fid in (a_id, b_id):
        if fid is None or fight_id is None:
            continue
        row = conn.execute(
            "SELECT promo_boost FROM fighters WHERE fighter_id=?",
            (fid,),
        ).fetchone()
        if not row:
            continue
        cur_pb = row[0] if row[0] is not None else 0

        # Previous fight date (before this one) — used as the lower
        # bound on the post_date window.
        prev_row = conn.execute(
            "SELECT MAX(event_date) FROM fight_history "
            "WHERE fighter_id=? AND fight_id <> ?",
            (fid, fight_id),
        ).fetchone()
        since_date = prev_row[0] if prev_row and prev_row[0] else '1970-01-01'

        # This fight's date — upper bound on the post_date window.
        fight_date_row = conn.execute(
            "SELECT event_date FROM fight_history "
            "WHERE fighter_id=? AND fight_id=? "
            "ORDER BY event_date DESC LIMIT 1",
            (fid, fight_id),
        ).fetchone()
        if not fight_date_row:
            continue
        fight_date = fight_date_row[0]

        n_viral = conn.execute(
            "SELECT COUNT(*) FROM social_posts "
            "WHERE fighter_id=? AND engagement > ? "
            "AND post_date > ? AND post_date <= ?",
            (fid, PROMO_BOOST_ENGAGEMENT_THRESHOLD,
             since_date, fight_date),
        ).fetchone()[0]
        if n_viral > 0:
            new_pb = max(-100, min(100, cur_pb + n_viral))
            if new_pb != cur_pb:
                conn.execute(
                    "UPDATE fighters SET promo_boost=?, "
                    "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                    (new_pb, fid),
                )


