# Constants
# ----------------------------------------------------------------

# Morale bounds — never 0 (broken fighter) or 100 (complacent). The
# brief mandates this clamp: a fighter at 0 morale would be a wreck,
# and a fighter at 100 would have nothing to chase. The [10, 95]
# band keeps morale impactful without breaking the sim.
MORALE_FLOOR = 10
MORALE_CEIL = 95

# Regression-to-mean anchor for weekly drift. Fighters naturally
# trend back toward "average mood" over time — the euphoria of a
# win fades, the sting of a loss softens. ±1 per week toward 50.
MORALE_MEAN = 50

# Days without a fight before "ring rust" kicks in. 90 days = ~3
# months. A fighter who hasn't fought in 3+ months loses -2 morale
# per week (forgotten by fans, questioning themselves).
RING_RUST_DAYS = 90

# Win-streak threshold for the weekly "riding high" bonus. A fighter
# on a 5+ win streak gains +1 morale per week (confidence compounds).
WIN_STREAK_HIGH = 5

# Losing-streak penalty parameters. -3 per consecutive loss beyond
# the first, capped at -9 (3 additional losses worth).
LOSS_STREAK_PENALTY_PER = -3
LOSS_STREAK_PENALTY_CAP = -9

# Winning-streak bonus parameters. +2 per consecutive win beyond the
# first, capped at +6 (3 additional wins worth).
WIN_STREAK_BONUS_PER = 2
WIN_STREAK_BONUS_CAP = 6

# Age thresholds for injury_proneness (+1/year over 30) and
# weight_cut_difficulty (+1/year over 32). The body wears down.
INJURY_PRONENESS_AGE_THRESHOLD = 30
WEIGHT_CUT_DIFFICULTY_AGE_THRESHOLD = 32

# Exciting-fight threshold: >10 beats in round 1 = exciting (the
# fight had early pace + action, not a feeling-out round).
EXCITING_FIGHT_BEAT_THRESHOLD = 10

# Cap for consistency growth (per the brief).
CONSISTENCY_CAP = 90
# Cap + floor for clutch_factor (per the brief).
CLUTCH_FACTOR_CAP = 90
CLUTCH_FACTOR_FLOOR = 20

# Promo_boost viral-post engagement threshold.
PROMO_BOOST_ENGAGEMENT_THRESHOLD = 50

# Personality field bounds (Stage5-Final). The schema CHECK is
# BETWEEN 0 AND 100, but we clamp tighter to [10, 95] per the brief
# — a 0-grit fighter would be a wreck, a 100-ambition fighter would
# be insatiable. Matches the morale [10, 95] clamp pattern.
PERSONALITY_FLOOR = 10
PERSONALITY_CEIL = 95

# Losing-streak / winning-streak thresholds for the weekly
# personality drift (Stage5-Final). Fighters on 3+ loss streaks get
# the "desperate to prove themselves" grit + ambition bumps; fighters
# on 5+ win streaks get the "comfortable" ambition drop.
LOSS_STREAK_GRIT_ONSET = 3
WIN_STREAK_COMFORT_ONSET = 5


