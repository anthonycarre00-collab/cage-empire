def _process_title_change(conn, event):
    """Subscriber for TITLE_CHANGED.

    New champion: +15 morale (career-defining moment).
    Dethroned champion: -15 morale (lost the belt).

    The TITLE_CHANGED event is published AFTER FIGHT_RESOLVED, so the
    fight-outcome morale change has already been applied. This
    subscriber adds the title-specific boost/penalty on top.

    For a vacant title claim, there is no dethroned champion, so the
    -15 penalty is skipped. We detect this by checking
    titles.title_reigns_count > 1 (a dethronement bumps the count
    past 1; a vacant claim increments it from 0 to 1).
    """
    title_id = event.get('title_id')
    fight_id = event.get('fight_id')
    if fight_id is None:
        return

    # Find the winner + loser of the title fight.
    row = conn.execute(
        "SELECT winner_fighter_id, loser_fighter_id, result_type "
        "FROM fights WHERE fight_id=?",
        (fight_id,),
    ).fetchone()
    if not row:
        return
    winner_id, loser_id, _ = row

    if winner_id is not None:
        m = _get_morale(conn, winner_id)
        _set_morale(conn, winner_id, m + 15, update_snapshot=True)

    if loser_id is not None and title_id is not None:
        # Only apply -15 if this was an actual dethronement (not a
        # vacant title being claimed). title_reigns_count > 1 means
        # the title was held before this fight.
        title_row = conn.execute(
            "SELECT title_reigns_count FROM titles WHERE title_id=?",
            (title_id,),
        ).fetchone()
        if title_row and (title_row[0] or 0) > 1:
            m = _get_morale(conn, loser_id)
            _set_morale(conn, loser_id, m - 15, update_snapshot=True)


