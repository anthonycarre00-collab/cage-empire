def register_subscribers():
    """Register all morale + dynamic-fields subscribers on the event bus.

    Call once at startup (UI App.__init__, test setup, etc.). The
    function is safe to call multiple times — the event bus's
    subscribe() simply appends to its subscriber list. For test
    isolation, call reset_bus() first to clear any prior registrations.

    Subscribes to:
      FIGHT_RESOLVED  → _process_fight
      TITLE_CHANGED   → _process_title_change
      TICK_ADVANCED   → _process_tick
      CAMP_COMPLETED  → _process_camp_completed
      CAMP_INJURY     → _process_camp_injury
      FIGHT_CANCELLED → _process_fight_cancelled
    """
    from event_bus import get_bus, Events
    bus = get_bus()
    bus.subscribe(
        Events.FIGHT_RESOLVED, _process_fight,
        name="morale.process_fight",
    )
    bus.subscribe(
        Events.TITLE_CHANGED, _process_title_change,
        name="morale.process_title_change",
    )
    bus.subscribe(
        Events.TICK_ADVANCED, _process_tick,
        name="morale.process_tick",
    )
    bus.subscribe(
        Events.CAMP_COMPLETED, _process_camp_completed,
        name="morale.process_camp_completed",
    )
    bus.subscribe(
        Events.CAMP_INJURY, _process_camp_injury,
        name="morale.process_camp_injury",
    )
    bus.subscribe(
        Events.FIGHT_CANCELLED, _process_fight_cancelled,
        name="morale.process_fight_cancelled",
    )
