def _process_tick(conn, event):
    """Subscriber for TICK_ADVANCED.

    WEEKLY actions (when current_day is a multiple of 7):
      - Morale drift toward 50 (±1).
      - Ring rust: -2 if fighter hasn't fought in 90+ days.
      - Win-streak bonus: +1 if fighter on 5+ win streak.
      - Injury recovery scan: +5 for each injury that recovered today.
      - Stage5-Final: personality field drift (grit, ambition,
        resilience) for streaks + injury comebacks.

    BIRTHDAY actions (current_date matches a fighter's DOB month/day):
      - injury_proneness: +1 per year of age over 30.
      - weight_cut_difficulty: +1 per year of age over 32.
    """
    current_date = event.get('current_date')
    if not current_date:
        return

    if _is_weekly_tick(conn):
        _weekly_morale_drift(conn, current_date)
        _weekly_personality_drift(conn, current_date)
        _weekly_snapshot_refresh(conn)

    # Birthday aging — checked on every tick (cheap).
    _birthday_aging(conn, current_date)


def _weekly_morale_drift(conn, current_date):
    """Drift every active fighter's morale toward 50 by ±1, apply ring
    rust (-2) for 90+ days without a fight, apply +1 win-streak bonus
    for 5+ win streaks. Also scan for injury recoveries today (+5)."""
    rows = conn.execute(
        "SELECT f.fighter_id, fp.morale, fc.win_streak "
        "FROM fighters f "
        "JOIN fighter_personality fp ON fp.fighter_id=f.fighter_id "
        "LEFT JOIN fighter_career fc ON fc.fighter_id=f.fighter_id "
        "WHERE f.is_active=1 AND f.is_retired=0"
    ).fetchall()

    for fighter_id, morale, ws in rows:
        morale = morale if morale is not None else 50
        ws = ws or 0
        new_morale = morale

        # Drift toward 50 by ±1.
        if morale < MORALE_MEAN:
            new_morale += 1
        elif morale > MORALE_MEAN:
            new_morale -= 1

        # Ring rust — 90+ days since last fight.
        days = _days_since_last_fight(conn, fighter_id, current_date)
        if days is not None and days >= RING_RUST_DAYS:
            new_morale -= 2

        # Win-streak bonus — riding high.
        if ws >= WIN_STREAK_HIGH:
            new_morale += 1

        new_morale = _clamp_morale(new_morale)
        if new_morale != morale:
            conn.execute(
                "UPDATE fighter_personality SET morale=? "
                "WHERE fighter_id=?",
                (new_morale, fighter_id),
            )

    # Injury recovery scan (INJURY_RECOVERED surrogate). The
    # tick_processor._check_injury_recovery function (which runs
    # BEFORE TICK_ADVANCED is published) sets actual_return_date =
    # current_date and is_active=0 for recovered injuries. We pick
    # those up here.
    rec_rows = conn.execute(
        "SELECT fighter_id FROM injuries "
        "WHERE is_active=0 AND actual_return_date=?",
        (current_date,),
    ).fetchall()
    for (rec_fid,) in rec_rows:
        m = _get_morale(conn, rec_fid)
        _set_morale(conn, rec_fid, m + 5, update_snapshot=False)


def _weekly_snapshot_refresh(conn):
    """Refresh descriptor snapshots for all active fighters (batch).

    The weekly drift loop updates morale without refreshing snapshots
    (to avoid N snapshot writes per weekly tick). We refresh them all
    here in one pass so the UI sees the new morale tiers.
    """
    rows = conn.execute(
        "SELECT fighter_id FROM fighters "
        "WHERE is_active=1 AND is_retired=0"
    ).fetchall()
    for (fid,) in rows:
        _refresh_snapshot(conn, fid)


def _weekly_personality_drift(conn, current_date):
    """Stage5-Final — weekly personality field drift.

    Per the brief:
      - Fighter on 3+ loss streak: grit +1, ambition +2 (desperate
        to prove themselves).
      - Fighter on 5+ win streak: ambition -1 (comfortable).
      - Fighter who just returned from injury (detected via
        actual_return_date check): resilience +2, grit +1.

    Mutually exclusive per fighter per tick:
      - A 3+ loss streak + injury recovery in the same week is
        possible — both fire (the fighter is doubly tested). The
        resilience +2 (comeback) and grit +1 (loss streak) compound.
      - A 5+ win streak + injury recovery is rare (winning fighters
        don't usually get injured) but if it happens, the win streak
        comfort (-1 ambition) and the comeback resilience (+2) both
        fire — the fighter is "comfortably on top, just got healthy".

    All updates use _set_personality_field with update_snapshot=False
    (the caller's _weekly_snapshot_refresh handles the snapshot write
    in one batched pass).
    """
    # ---- streak-based grit + ambition shifts ----
    rows = conn.execute(
        "SELECT f.fighter_id, fc.win_streak, fc.loss_streak, "
        "fp.grit, fp.ambition "
        "FROM fighters f "
        "JOIN fighter_personality fp ON fp.fighter_id=f.fighter_id "
        "LEFT JOIN fighter_career fc ON fc.fighter_id=f.fighter_id "
        "WHERE f.is_active=1 AND f.is_retired=0"
    ).fetchall()
    for fighter_id, ws, ls, cur_grit, cur_amb in rows:
        ws = ws or 0
        ls = ls or 0
        cur_grit = cur_grit if cur_grit is not None else 50
        cur_amb = cur_amb if cur_amb is not None else 50
        if ls >= LOSS_STREAK_GRIT_ONSET:
            # Desperate to prove themselves.
            _set_personality_field(
                conn, fighter_id, "grit", cur_grit + 1,
                update_snapshot=False,
            )
            _set_personality_field(
                conn, fighter_id, "ambition", cur_amb + 2,
                update_snapshot=False,
            )
        elif ws >= WIN_STREAK_COMFORT_ONSET:
            # Comfortable — riding high.
            _set_personality_field(
                conn, fighter_id, "ambition", cur_amb - 1,
                update_snapshot=False,
            )

    # ---- injury comeback: resilience +2, grit +1 ----
    # Same detection pattern as _weekly_morale_drift's injury scan
    # — injuries with is_active=0 AND actual_return_date == current_
    # date were just recovered by tick_processor._check_injury_
    # recovery (which runs BEFORE TICK_ADVANCED is published).
    rec_rows = conn.execute(
        "SELECT DISTINCT fighter_id FROM injuries "
        "WHERE is_active=0 AND actual_return_date=?",
        (current_date,),
    ).fetchall()
    for (rec_fid,) in rec_rows:
        row = conn.execute(
            "SELECT grit, resilience FROM fighter_personality "
            "WHERE fighter_id=?",
            (rec_fid,),
        ).fetchone()
        if not row:
            continue
        cur_grit, cur_res = row
        cur_grit = cur_grit if cur_grit is not None else 50
        cur_res = cur_res if cur_res is not None else 50
        _set_personality_field(
            conn, rec_fid, "resilience", cur_res + 2,
            update_snapshot=False,
        )
        _set_personality_field(
            conn, rec_fid, "grit", cur_grit + 1,
            update_snapshot=False,
        )


def _birthday_aging(conn, current_date):
    """On a fighter's birthday, age up injury_proneness and
    weight_cut_difficulty per the brief."""
    try:
        dt = datetime.strptime(current_date, "%Y-%m-%d")
    except (ValueError, TypeError):
        return

    rows = conn.execute(
        "SELECT fighter_id, date_of_birth, injury_proneness, "
        "weight_cut_difficulty FROM fighters "
        "WHERE is_active=1 AND is_retired=0 "
        "AND date_of_birth IS NOT NULL"
    ).fetchall()

    for fighter_id, dob, cur_pron, cur_wcd in rows:
        if not dob:
            continue
        try:
            dob_dt = datetime.strptime(dob, "%Y-%m-%d")
        except (ValueError, TypeError):
            continue

        # Birthday match (month + day).
        if dob_dt.month != dt.month or dob_dt.day != dt.day:
            continue

        # Compute age. Today IS the birthday so the year-only diff
        # is correct, but be defensive.
        age = dt.year - dob_dt.year
        if (dt.month, dt.day) < (dob_dt.month, dob_dt.day):
            age -= 1

        cur_pron = cur_pron if cur_pron is not None else 50
        cur_wcd = cur_wcd if cur_wcd is not None else 50
        updates = {}
        if age > INJURY_PRONENESS_AGE_THRESHOLD:
            new_pron = min(100, cur_pron + 1)
            if new_pron != cur_pron:
                updates['injury_proneness'] = new_pron
        if age > WEIGHT_CUT_DIFFICULTY_AGE_THRESHOLD:
            new_wcd = min(100, cur_wcd + 1)
            if new_wcd != cur_wcd:
                updates['weight_cut_difficulty'] = new_wcd
        if updates:
            set_clause = ", ".join(f"{k}=?" for k in updates)
            params = list(updates.values()) + [fighter_id]
            conn.execute(
                f"UPDATE fighters SET {set_clause}, "
                "updated_at=CURRENT_TIMESTAMP WHERE fighter_id=?",
                params,
            )
            _refresh_snapshot(conn, fighter_id)


