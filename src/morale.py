"""CAGE EMPIRE Fighter Morale + Dynamic Meta-Fields System (Phase A — A1 + A10).

This module wires the two biggest "frozen field" gaps identified in
docs/FULL_BUILD_AUDIT.md:

  A1 — fighter_personality.morale (0-100, clamped to [10, 95]).
       The fight engine reads this column via _load_fighter_stats, but
       before this task NO system ever wrote to it after seed time.
       Wins, losses, injuries, title changes, camp completions, and
       time all left it frozen at the seed default of 50.

  A10 — fighters.* dynamic meta-fields (marketability, fan_friendliness,
       consistency, clutch_factor, promo_boost, injury_proneness,
       weight_cut_difficulty). Same problem: set at seed, never updated.

The fix is entirely event-bus-driven (CONVENTIONS §15.4 — no new inline
side effects added to resolve_next_fight or run_tick). The module
subscribes to 6 events:

  FIGHT_RESOLVED  → winner/loser morale swings + dynamic field bumps
  TITLE_CHANGED   → new champion +15, dethroned champion -15
  TICK_ADVANCED   → weekly drift toward 50, ring rust, win-streak
                    bonus, birthday-based aging of injury_proneness
                    and weight_cut_difficulty, injury-recovery morale
  CAMP_COMPLETED  → +3 morale (training went well)
  CAMP_INJURY     → -5 morale (training setback)
  FIGHT_CANCELLED → weight-cut miss: -5 (fighter who missed) / -3
                    (opponent). Subscribed for forward-compat; the
                    event is not yet published by app.py (Phase A5
                    wires news coverage and will publish it).

INJURY_CREATED / INJURY_RECOVERED are NOT subscribed directly because
the engine does not publish them. Instead:
  - New injuries are detected by scanning the `injuries` table for new
    rows for the resolved fight_id (inside the FIGHT_RESOLVED
    subscriber).
  - Recovered injuries are detected by scanning for
    `actual_return_date == current_date` (inside the TICK_ADVANCED
    subscriber).

VOICE LAYER (CONVENTIONS §14): the morale system produces NO player-
facing text. Morale is internal state that feeds the fight engine
(via _load_fighter_stats) and the descriptor snapshot (via
update_fighter_descriptor_snapshot). The morale descriptor itself is
generated by voice.py's PERSONALITY_DESCRIPTORS['morale'] when the
snapshot is refreshed. No raw numbers leak because morale writes no
prose of its own.

DESIGN LAW (CONVENTIONS §13):
  - Growth: morale drives fight performance (the beat engine loads it
    via _load_fighter_stats and uses it in pressure_response). A
    high-morale fighter gets a psychological lift; a low-morale
    fighter underperforms. The feedback loop is now CLOSED — wins
    boost morale → next fight gets a boost → more wins.
  - Conflict: losses hurt. KO losses hurt more. Losing streaks
    compound the pain. The "will he bounce back?" thread is now a
    real sim state, not just a storyline seed.
  - Anticipation: a champion with maxed morale creates the
    "complacency upset?" thread. A fighter on a skid creates the
    "must-win fight" thread. A prospect with rising morale creates
    the "is he the real deal?" thread.

USAGE:
  from morale import register_subscribers
  register_subscribers()  # call once at startup (UI App.__init__,
                          # test setup). Safe to call multiple times.
  # The morale system processes events automatically via the bus.
  # No need to call any function directly.
"""

